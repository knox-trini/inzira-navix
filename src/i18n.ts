export function getInitial(): "en" | "rw" | "fr" | "sw" {
  if (typeof window === "undefined") return "en";
  const stored = localStorage.getItem("lang");
  if (stored && ["en", "rw", "fr", "sw"].includes(stored)) return stored as "en" | "rw" | "fr" | "sw";
  const nav = navigator.language?.slice(0, 2).toLowerCase();
  if (nav && ["en", "rw", "fr", "sw"].includes(nav)) return nav as "en" | "rw" | "fr" | "sw";
  return "en";
}

